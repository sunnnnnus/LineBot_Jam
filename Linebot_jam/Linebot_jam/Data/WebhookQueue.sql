-- Additive upgrade, also run automatically by WebhookBackgroundService.
CREATE TABLE IF NOT EXISTS "WEBHOOK_JOBS" (
    "EventId" TEXT PRIMARY KEY,
    "Sequence" BIGINT GENERATED ALWAYS AS IDENTITY,
    "Payload" TEXT NOT NULL,
    "ReceivedAt" TIMESTAMPTZ NOT NULL,
    "Processed" BOOLEAN NOT NULL DEFAULT FALSE,
    "ProcessingAttempts" INTEGER NOT NULL DEFAULT 0,
    "ReplyMessages" TEXT NULL,
    "Destination" TEXT NULL,
    "ReplyAttempted" BOOLEAN NOT NULL DEFAULT FALSE,
    "UsePush" BOOLEAN NOT NULL DEFAULT FALSE,
    "RetryKey" UUID NOT NULL,
    "PushStartedAt" TIMESTAMPTZ NULL,
    "DeliveryAttempts" INTEGER NOT NULL DEFAULT 0,
    "NextAttemptAt" TIMESTAMPTZ NOT NULL,
    "Finished" BOOLEAN NOT NULL DEFAULT FALSE,
    "LastError" TEXT NULL
);
CREATE INDEX IF NOT EXISTS "IX_WebhookJobs_Pending"
    ON "WEBHOOK_JOBS" ("Sequence") WHERE NOT "Processed";
CREATE INDEX IF NOT EXISTS "IX_WebhookJobs_Delivery"
    ON "WEBHOOK_JOBS" ("NextAttemptAt") WHERE "Processed" AND NOT "Finished";

CREATE TABLE IF NOT EXISTS "REMINDER_DISPATCHES" (
    "TaskId" INTEGER NOT NULL,
    "ReminderType" TEXT NOT NULL,
    "EventId" TEXT NOT NULL REFERENCES "WEBHOOK_JOBS" ("EventId") ON DELETE CASCADE,
    PRIMARY KEY ("TaskId", "ReminderType")
);
CREATE INDEX IF NOT EXISTS "IX_ReminderDispatches_EventId" ON "REMINDER_DISPATCHES" ("EventId");

CREATE TABLE IF NOT EXISTS "MAIL_SYNC_STATE" (
    "Account" TEXT PRIMARY KEY,
    "UserId" INTEGER NOT NULL REFERENCES "USERS" ("Id"),
    "StartedAt" TIMESTAMPTZ NOT NULL,
    "LastSyncedAt" TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS "MAIL_RECEIPTS" (
    "Key" TEXT PRIMARY KEY,
    "ReceivedAt" TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS "MAIL_PROPOSALS" (
    "Id" UUID PRIMARY KEY,
    "ReceiptKey" TEXT NOT NULL REFERENCES "MAIL_RECEIPTS" ("Key"),
    "UserId" INTEGER NOT NULL REFERENCES "USERS" ("Id"),
    "Content" VARCHAR(200) NOT NULL,
    "DueAt" TIMESTAMP NULL,
    "Status" TEXT NOT NULL,
    "Version" INTEGER NOT NULL,
    "TaskId" INTEGER NULL REFERENCES "TASKS" ("Id")
);
